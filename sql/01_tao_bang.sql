-- BƯỚC 1 (chỉ dùng cho dự án Supabase MỚI): tạo bảng + bảo mật. KHÔNG chứa dữ liệu.
-- Cách dùng: Supabase > SQL Editor > New query > dán toàn bộ > Run, sau đó chạy tiếp file 03_nang_cap_vi_tri_viec_lam.sql.
-- Dự án đang dùng (đã có dữ liệu) thì KHÔNG cần chạy file này, chỉ chạy file 03.
create table if not exists public.config (key text primary key, value text);
create table if not exists public.tasks (
    id bigint generated by default as identity primary key,
    title text not null, mo_ta text, loai text default 'Khác', uu_tien text default 'Bình thường',
    ngay_bd date not null, ngay_kt date not null, gio_bd text, gio_kt text, dia_diem text, nguoi_pt text,
    trang_thai text default 'Chưa thực hiện', ket_qua text, ghi_chu text, lanh_dao_giao text,
    thoi_han_vb date, lanh_dao_tham_dinh text, created_at timestamptz default now(),
    chu_tri boolean default true, phoi_hop text, loai_viec_bc text default 'Kế hoạch/thường xuyên',
    tu_danh_gia_cl text, truc text default 'Trục 1', nhom_ab text default 'A - Nhiệm vụ thường xuyên',
    can_cu_nv text, so_luong_ke_hoach integer default 1, nhom_kho text default 'N2',
    so_luong_thuc_te integer, he_so_chat_luong numeric default 1.0
);
create table if not exists public.next_week_tasks (
    id bigint generated by default as identity primary key,
    noi_dung text not null, phoi_hop text, thoi_gian_hoan_thanh text,
    tuan integer not null, nam integer not null, created_at timestamptz default now()
);
create index if not exists idx_tasks_ngay on public.tasks (ngay_bd, ngay_kt);
create index if not exists idx_next_week on public.next_week_tasks (nam, tuan);
alter table public.config enable row level security;
alter table public.tasks enable row level security;
alter table public.next_week_tasks enable row level security;
-- Bảo mật: chỉ tài khoản ĐÃ ĐĂNG NHẬP mới đọc/ghi được. Khách (anon) không thấy gì.
drop policy if exists "allow all - config" on public.config;
drop policy if exists "allow all - tasks" on public.tasks;
drop policy if exists "allow all - next_week_tasks" on public.next_week_tasks;
drop policy if exists "dn - config" on public.config;
drop policy if exists "dn - tasks" on public.tasks;
drop policy if exists "dn - next_week_tasks" on public.next_week_tasks;
create policy "dn - config" on public.config for all to authenticated using (true) with check (true);
create policy "dn - tasks" on public.tasks for all to authenticated using (true) with check (true);
create policy "dn - next_week_tasks" on public.next_week_tasks for all to authenticated using (true) with check (true);
